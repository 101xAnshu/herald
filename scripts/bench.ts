import { writeFileSync } from "node:fs";
import { cpus, totalmem } from "node:os";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const option = (name: string, fallback: string): string => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? fallback : (args[index + 1] ?? fallback);
};

const baseUrl = option("url", process.env["HERALD_API_URL"] ?? "http://localhost:3000");
const rate = Number(option("rate", "50"));
const duration = Number(option("duration", "10"));
const users = Number(option("users", "500"));
const concurrency = Number(option("concurrency", "20"));

const loadDemoKey = (): string => {
  const text = require("node:fs").readFileSync(resolve(process.cwd(), ".herald/demo.env"), "utf8") as string;
  const line = text.split("\n").find((entry) => entry.startsWith("HERALD_BOOKING_API_KEY="));
  return line?.split("=")[1] ?? "";
};

const apiKey = process.env["HERALD_BOOKING_API_KEY"] ?? loadDemoKey();
const total = Math.max(1, Math.round(rate * duration));
const latencies: number[] = [];
let accepted = 0;
let failed = 0;
let inFlight = 0;
let started = 0;

const sendOne = async (index: number): Promise<void> => {
  const externalId = `cust_${String((index % users) + 1).padStart(5, "0")}`;
  const startedAt = performance.now();

  try {
    const response = await fetch(`${baseUrl}/v1/events`, {
      method: "POST",
      headers: { authorization: `Bearer ${apiKey}`, "content-type": "application/json" },
      body: JSON.stringify({
        type: "booking.confirmed",
        schema_version: 1,
        recipient: { external_id: externalId },
        idempotency_key: `bench:${Date.now()}:${index}`,
        data: {
          booking_id: `bkg_bench_${index}`,
          service: "plumbing",
          pro_name: "Ravi",
          scheduled_for: "2026-11-02T10:00:00+05:30",
          address_label: "Home",
        },
      }),
    });

    if (!response.ok) {
      failed += 1;
      return;
    }

    await response.arrayBuffer();
    accepted += 1;
    latencies.push(performance.now() - startedAt);
  } catch {
    failed += 1;
  }
};

const percentile = (values: number[], p: number): number => {
  if (values.length === 0) {
    return 0;
  }

  const sorted = [...values].sort((left, right) => left - right);
  return sorted[Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length))] ?? 0;
};

const main = async (): Promise<void> => {
  const begin = Date.now();
  const active = new Set<Promise<void>>();

  while (started < total && Date.now() - begin < duration * 1000) {
    const task = sendOne(started).finally(() => active.delete(task));
    active.add(task);
    inFlight += 1;
    started += 1;

    if (active.size >= concurrency) {
      await Promise.race(active);
    }

    await new Promise((resolvePromise) => setTimeout(resolvePromise, Math.max(0, 1000 / rate)));
  }

  await Promise.all(active);

  const elapsed = (Date.now() - begin) / 1000;
  const p50 = percentile(latencies, 50);
  const p90 = percentile(latencies, 90);
  const p95 = percentile(latencies, 95);
  const p99 = percentile(latencies, 99);
  const mean = latencies.length === 0 ? 0 : latencies.reduce((sum, value) => sum + value, 0) / latencies.length;
  const min = latencies.length === 0 ? 0 : Math.min(...latencies);
  const max = latencies.length === 0 ? 0 : Math.max(...latencies);
  const throughput = accepted / elapsed;
  const loss = failed / Math.max(1, accepted + failed);

  const report = `# Ingest benchmark

Generated by \`pnpm bench\` on ${new Date().toISOString()}.

| Field | Value |
|---|---|
| Host | ${cpus()[0]?.model ?? "unknown"}, ${cpus().length} vCPU |
| Memory | ${(totalmem() / 1024 ** 3).toFixed(1)} GiB |
| API | ${baseUrl} |
| Target rate | ${rate} events/s |
| Duration | ${duration}s |
| Concurrency | ${concurrency} |
| Sent | ${accepted + failed} |
| Accepted | ${accepted} |
| Failed | ${failed} |
| Elapsed | ${elapsed.toFixed(1)}s |
| Throughput | ${throughput.toFixed(1)} events/s |
| Mean latency | ${mean.toFixed(1)} ms |
| Min latency | ${min.toFixed(1)} ms |
| p50 | ${p50.toFixed(1)} ms |
| p90 | ${p90.toFixed(1)} ms |
| p95 | ${p95.toFixed(1)} ms |
| p99 | ${p99.toFixed(1)} ms |
| Max latency | ${max.toFixed(1)} ms |
| Loss | ${(loss * 100).toFixed(2)}% |

The run drives \`POST /v1/events\` with unique idempotency keys. Delivery happens
asynchronously and is not part of the latency numbers. A loss rate above zero
means the accepted-event invariant did not hold under this offered load.
`;

  const path = resolve(process.cwd(), "docs/BENCH.md");
  writeFileSync(path, report);
  process.stdout.write(report);
  process.stdout.write(`\nwrote ${path}\n`);

  if (failed > 0) {
    process.exitCode = 1;
  }
};

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
